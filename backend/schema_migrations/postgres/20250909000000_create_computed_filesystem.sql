-- Create computed filesystem table for persisting filesystem tree data
-- migrate:up

CREATE TABLE computed_filesystem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id INTEGER NOT NULL REFERENCES repository(repository_id),
    path TEXT NOT NULL,
    parent_path TEXT,
    level INTEGER NOT NULL,
    node_data JSONB NOT NULL,

    UNIQUE(repository_id, path)
);

-- Core index for main access pattern: repository + parent_path + level filtering
CREATE INDEX idx_computed_fs_core
ON computed_filesystem(repository_id, parent_path, level);

-- migrate:down

DROP TABLE IF EXISTS computed_filesystem;