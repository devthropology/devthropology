-- Create computed_user_metrics table for storing computed user metrics
-- migrate:up

CREATE TABLE computed_user_metrics (
  computed_user_metrics_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES "user"(user_id),
  repository_id BIGINT NOT NULL REFERENCES repository(repository_id),
  metric_key TEXT NOT NULL,
  period TEXT NOT NULL,
  value BIGINT NOT NULL,
  rank INTEGER,
  rank_out_of INTEGER,
  inserted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  
  -- Prevent duplicate stats for same user/repo/metric/period combination
  UNIQUE (user_id, repository_id, metric_key, period)
);

-- Composite index for repository + user lookups (covers both access patterns)
CREATE INDEX ix_computed_user_metrics_repo_user
  ON computed_user_metrics (repository_id, user_id);

-- migrate:down

DROP TABLE IF EXISTS computed_user_metrics;
